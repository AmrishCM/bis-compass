interface LanguageContextType {
  language: SupportedLanguage;
  currentLanguage: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string, defaultVal?: string) => string;
  translateDynamic: (text: string) => Promise<string>;
  translateBatchDynamic: (texts: string[]) => Promise<string[]>;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  currentLanguage: 'en',
  setLanguage: () => {},
  t: (key: string, defaultVal?: string) => defaultVal || key,
  translateDynamic: async (text: string) => text,
  translateBatchDynamic: async (texts: string[]) => texts,
});

const dynamicCache = new Map<string, string>();

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<SupportedLanguage>(() => {
    const saved = localStorage.getItem('bis_compass_lang');
    if (saved && SUPPORTED_LANGUAGES.some(l => l.code === saved)) {
      return saved as SupportedLanguage;
    }
    return 'en';
  });

  const setLanguage = (lang: SupportedLanguage) => {
    setLanguageState(lang);
    localStorage.setItem('bis_compass_lang', lang);
  };

  const t = (key: string, defaultVal?: string): string => {
    const dict = STATIC_TRANSLATIONS[language] || STATIC_TRANSLATIONS.en;
    if (dict && dict[key]) {
      return dict[key];
    }
    const enDict = STATIC_TRANSLATIONS.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return defaultVal || key;
  };

  const translateDynamic = async (text: string): Promise<string> => {
    if (language === 'en' || !text || !text.trim()) return text;
    const cacheKey = `${language}:${text}`;
    if (dynamicCache.has(cacheKey)) {
      return dynamicCache.get(cacheKey)!;
    }

    try {
      const data = await api.translateText(text, language);
      const translated = data?.translated_text || text;
      dynamicCache.set(cacheKey, translated);
      return translated;
    } catch {
      return text;
    }
  };

  const translateBatchDynamic = async (texts: string[]): Promise<string[]> => {
    if (language === 'en' || !texts || texts.length === 0) return texts;

    const results: string[] = [];
    const missing: { text: string; index: number }[] = [];

    texts.forEach((text, i) => {
      const cacheKey = `${language}:${text}`;
      if (dynamicCache.has(cacheKey)) {
        results[i] = dynamicCache.get(cacheKey)!;
      } else {
        missing.push({ text, index: i });
      }
    });

    if (missing.length === 0) {
      return results;
    }

    try {
      const res = await api.translateBatch(missing.map(m => m.text), language);
      if (res && res.translations) {
        res.translations.forEach((trans: string, k: number) => {
          const original = missing[k].text;
          const origIdx = missing[k].index;
          dynamicCache.set(`${language}:${original}`, trans);
          results[origIdx] = trans;
        });
      }
    } catch {
      missing.forEach(m => {
        results[m.index] = m.text;
      });
    }

    return results;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        currentLanguage: language,
        setLanguage,
        t,
        translateDynamic,
        translateBatchDynamic
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
